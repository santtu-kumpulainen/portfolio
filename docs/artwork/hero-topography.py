"""Generate the decorative hero backdrop: original topographic contours (marching squares).

Usage: python3 docs/artwork/hero-topography.py > public/artwork/hero-topography.svg
Edit HILLS to reshape the terrain; the mass stays on the right so the hero text stays readable.
"""
import math
import sys

W, H = 1440, 760
STEP = 10
NX, NY = W // STEP + 1, H // STEP + 1

# Gaussian hills; mass sits on the right so the text column stays quiet.
HILLS = [
    (1170, 260, 240, 1.00),
    (960, 580, 180, 0.70),
    (1400, 660, 170, 0.60),
    (840, 170, 150, 0.45),
    (1330, 40, 120, 0.35),
]


def field(x, y):
    v = 0.0
    for cx, cy, r, a in HILLS:
        d2 = ((x - cx) ** 2 + (y - cy) ** 2) / (r * r)
        v += a * math.exp(-d2)
    # gentle warp so contours are not perfect circles
    v += 0.045 * math.sin(x / 170 + y / 260) + 0.03 * math.cos(y / 120 - x / 310)
    return v


grid = [[field(i * STEP, j * STEP) for i in range(NX)] for j in range(NY)]


def point(edge, level):
    (i1, j1), (i2, j2) = edge
    v1, v2 = grid[j1][i1], grid[j2][i2]
    t = (level - v1) / (v2 - v1)
    return (i1 + t * (i2 - i1)) * STEP, (j1 + t * (j2 - j1)) * STEP


def contours(level):
    adj = {}
    pts = {}

    def link(a, b):
        for e in (a, b):
            if e not in pts:
                pts[e] = point(e, level)
        adj.setdefault(a, []).append(b)
        adj.setdefault(b, []).append(a)

    for j in range(NY - 1):
        for i in range(NX - 1):
            c = [(i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1)]
            inside = [grid[y][x] > level for x, y in c]
            edges = []
            for k in range(4):
                a, b = c[k], c[(k + 1) % 4]
                if inside[k] != inside[(k + 1) % 4]:
                    edges.append(tuple(sorted((a, b))))
            if len(edges) == 2:
                link(edges[0], edges[1])
            elif len(edges) == 4:
                link(edges[0], edges[1])
                link(edges[2], edges[3])

    seen = set()
    lines = []
    # start from open ends first, then closed loops
    starts = [e for e, n in adj.items() if len(n) == 1] + list(adj)
    for s in starts:
        if s in seen:
            continue
        line = [s]
        seen.add(s)
        cur = s
        while True:
            nxt = [n for n in adj[cur] if n not in seen]
            if not nxt:
                break
            cur = nxt[0]
            seen.add(cur)
            line.append(cur)
        closed = len(line) > 2 and s in adj[cur]
        lines.append(([pts[e] for e in line], closed))
    return lines


def rdp(p, eps):
    if len(p) < 3:
        return p
    (x1, y1), (x2, y2) = p[0], p[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-9
    dmax, idx = 0, 0
    for k in range(1, len(p) - 1):
        d = abs(dy * p[k][0] - dx * p[k][1] + x2 * y1 - y2 * x1) / n
        if d > dmax:
            dmax, idx = d, k
    if dmax > eps:
        return rdp(p[: idx + 1], eps)[:-1] + rdp(p[idx:], eps)
    return [p[0], p[-1]]


def fmt(v):
    return str(round(v))


def path(p, closed):
    if closed:
        # split the loop so the simplifier never sees identical endpoints
        h = len(p) // 2
        p = rdp(p[: h + 1], 1.4)[:-1] + rdp(p[h:] + [p[0]], 1.4)
    else:
        p = rdp(p, 1.4)
    if len(p) < 3:
        return None
    # quadratic smoothing through midpoints
    d = [f"M{fmt(p[0][0])} {fmt(p[0][1])}"]
    for k in range(1, len(p) - 1):
        mx, my = (p[k][0] + p[k + 1][0]) / 2, (p[k][1] + p[k + 1][1]) / 2
        d.append(f"Q{fmt(p[k][0])} {fmt(p[k][1])} {fmt(mx)} {fmt(my)}")
    d.append(f"L{fmt(p[-1][0])} {fmt(p[-1][1])}")
    return "".join(d)


vmax = max(max(r) for r in grid)
LO = 0.1
levels = [LO + (vmax - 0.04 - LO) * k / 15 for k in range(16)]
out_minor, out_major = [], []
for n, lv in enumerate(levels):
    for p, closed in contours(lv):
        d = path(p, closed)
        if d:
            (out_major if n % 4 == 3 else out_minor).append(d)

py, px = max(((j * STEP, i * STEP) for j in range(NY) for i in range(NX)), key=lambda t: grid[t[0] // STEP][t[1] // STEP])

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" fill="none" stroke-linecap="round" stroke-linejoin="round">
  <!-- Decorative hero backdrop: original topographic contours.
       Generated by docs/artwork/hero-topography.py; edit the script, not this file.
       Colors come from the design tokens: border #292e35, text-subtle #7d848e, accent #3b82f6. -->
  <g stroke="#292e35" stroke-width="1">
    {chr(10).join('    <path d="' + d + '"/>' for d in out_minor).strip()}
  </g>
  <g stroke="#7d848e" stroke-width="1" stroke-opacity="0.45">
    {chr(10).join('    <path d="' + d + '"/>' for d in out_major).strip()}
  </g>
  <!-- Survey marker on the highest point -->
  <g stroke="#3b82f6" stroke-width="1.25">
    <circle cx="{px}" cy="{py}" r="4"/>
    <path d="M{px} {py-16}v8M{px} {py+8}v8M{px-16} {py}h8M{px+8} {py}h8"/>
  </g>
</svg>
"""
sys.stdout.write(svg)
